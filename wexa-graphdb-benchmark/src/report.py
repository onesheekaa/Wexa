"""
Reads results/*.json (one per platform, produced by src/runner.py) and
writes RESULTS.md with formatted tables plus PNG bar charts.

Run: python -m src.report
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"
CHARTS_DIR = RESULTS_DIR / "charts"
CHARTS_DIR.mkdir(exist_ok=True)


def load_all() -> dict:
    return {json.loads(f.read_text())["platform"]: json.loads(f.read_text())
            for f in sorted(RESULTS_DIR.glob("*.json"))}


def table(headers, rows) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def bar_chart(title, labels, values, ylabel, filename) -> Path:
    plt.figure(figsize=(7, 4))
    plt.bar(labels, values)
    plt.title(title)
    plt.ylabel(ylabel)
    plt.xticks(rotation=20)
    plt.tight_layout()
    path = CHARTS_DIR / filename
    plt.savefig(path)
    plt.close()
    return path.relative_to(RESULTS_DIR.parent)


def build_report() -> None:
    platforms = load_all()
    names = list(platforms.keys())
    if not names:
        print("no results/*.json found yet - run src/runner.py first")
        return

    out = [
        "# Benchmark Results\n",
        "Auto-generated by `src/report.py` from `results/*.json`. "
        "Re-run the report script after re-running benchmarks rather than editing this by hand.\n",
    ]

    rows = [[n, platforms[n]["ingest"]["nodes_per_second"], platforms[n]["ingest"]["rels_per_second"],
             platforms[n]["ingest"]["total_wall_clock_seconds"]] for n in names]
    out.append("## Data Loading\n")
    out.append(table(["Platform", "Nodes/s", "Rels/s", "Total load time (s)"], rows))
    chart = bar_chart("Ingest throughput", names,
                       [platforms[n]["ingest"]["rels_per_second"] for n in names],
                       "relationships/second", "ingest_throughput.png")
    out.append(f"\n![ingest throughput]({chart})\n")

    out.append("\n## Traversal latency (ms)\n")
    for hop in ("1_hop", "2_hop", "3_hop"):
        rows = [[n, platforms[n]["traversals"][hop]["p50_ms"], platforms[n]["traversals"][hop]["p95_ms"]]
                for n in names]
        out.append(f"### {hop.replace('_', '-')}\n")
        out.append(table(["Platform", "p50 (ms)", "p95 (ms)"], rows))
        out.append("")

    out.append("\n## Lookups (ms)\n")
    rows = [[n, platforms[n]["lookups"]["point_lookup"]["p50_ms"], platforms[n]["lookups"]["point_lookup"]["p95_ms"],
             platforms[n]["lookups"]["filtered_lookup"]["p50_ms"], platforms[n]["lookups"]["filtered_lookup"]["p95_ms"]]
            for n in names]
    out.append(table(["Platform", "Point p50", "Point p95", "Filtered p50", "Filtered p95"], rows))

    out.append("\n## Aggregation (ms)\n")
    rows = [[n, platforms[n]["aggregation"]["p50_ms"], platforms[n]["aggregation"]["p95_ms"]] for n in names]
    out.append(table(["Platform", "p50 (ms)", "p95 (ms)"], rows))

    out.append("\n## Mixed read/write throughput (qps)\n")
    concurrencies = sorted({k for n in names for k in platforms[n]["mixed_workload"]})
    rows = [[n] + [platforms[n]["mixed_workload"].get(c, {}).get("throughput_qps", "n/a") for c in concurrencies]
            for n in names]
    out.append(table(["Platform"] + concurrencies, rows))

    out.append("\n## Footprint\n")
    for n in names:
        out.append(f"- **{n}**: `{platforms[n]['footprint']}`")

    (RESULTS_DIR.parent / "RESULTS.md").write_text("\n".join(out))
    print("wrote RESULTS.md")


if __name__ == "__main__":
    build_report()
